CATEGORY_MAP = {c.slug: c for c in CATEGORIES}
TOOL_MAP = {t.slug: t for t in TOOLS}


def tools_in(category: str) -> list[Tool]:
    return [t for t in TOOLS if t.category == category]


def related_tools(tool: Tool) -> list[Tool]:
    return [TOOL_MAP[s] for s in tool.related if s in TOOL_MAP]


@lru_cache(maxsize=1)
def search_index() -> dict:
    return {
        "categories": [{"slug": c.slug, "name": c.name} for c in CATEGORIES],
        "tools": [
            {
                "slug": t.slug, "name": t.name, "h1": t.h1, "blurb": t.blurb, "category": t.category,
                "categoryName": CATEGORY_MAP[t.category].name, "icon": t.icon, "accepts": list(t.accepts),
                "keywords": list(t.keywords), "url": t.path,
            }
            for t in TOOLS
        ],
    }
